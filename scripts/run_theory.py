"""Theoretical analysis: Why does A_lin predict steering?

Tests the hypothesis: steering works when the steering direction d,
projected through the model's own readout function C = W_U @ LN,
assigns high weight to the target token. That is:

    ΔP ∝ C(d)_target = (W_U @ LN(d))_target

This gives a mechanistic explanation: A_lin measures whether the concept
is aligned with the unembedding's column space. The steering direction
(difference of means) inherits this alignment.

Also measures collateral damage: KL divergence on unrelated prompts
when steering is applied.

Usage:
    python scripts/run_theory_analysis.py --model google/gemma-2-2b --device cuda
    python scripts/run_theory_analysis.py --model Qwen/Qwen2.5-1.5B --device cuda
    python scripts/run_theory_analysis.py --model EleutherAI/pythia-2.8b-deduped --device cuda
"""

